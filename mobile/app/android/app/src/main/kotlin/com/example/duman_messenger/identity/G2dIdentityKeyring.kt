/**
 * G2-D Android Keystore wrapping adapter.
 *
 * This file owns exactly one cryptographic job: seal and open small byte
 * payloads with an AES-256-GCM key that lives in the Android Keystore and is
 * never exportable. It does not generate identity keys, it does not decide what
 * an identity is, and it never guesses: every failure mode below is a distinct
 * typed error, because "could not decrypt" and "there is no key" have different
 * consequences for the caller (the first is corruption, the second is a missing
 * key, and neither may silently become "start over").
 *
 * Design constraints that shaped it:
 *
 * * API 27 is the floor. `KeyGenParameterSpec` (API 23) and AES-GCM in the
 *   Keystore are available there, so a wrapping key is real hardware-or-software
 *   Keystore material on the oldest supported device.
 * * The iv is generated by the Keystore (`setRandomizedEncryptionRequired`), so
 *   a caller cannot reuse an iv even by mistake.
 * * Associated data binds the format version, the record generation and the
 *   key id, so a replayed, downgraded or re-keyed blob fails authentication
 *   instead of decrypting to something plausible.
 * * Byte buffers holding plaintext are zeroed as soon as the caller no longer
 *   needs them. This is best effort: the JVM may have copied a buffer, and
 *   Strings cannot be cleared at all, so the payload placed here must never be
 *   long-lived secret key material that we cannot clear.
 *
 * Ed25519 and X25519 identity keys are **not** hardware keys on API 27. Nothing
 * here claims otherwise: this adapter reports what it measured about its own
 * AES key, and the Dart side refuses any stronger claim.
 */

/** Keystore provider name. Exposed for diagnostics; not a security claim. */
internal const val G2D_KEYSTORE_PROVIDER = "AndroidKeyStore"

/** Alias of the long-lived wrapping key that protects identity data at rest. */
internal const val G2D_WRAPPING_KEY_ALIAS = "g2d.identity.wrap.v1"

/** Alias used by the capability probe; created and deleted on every probe. */
internal const val G2D_PROBE_KEY_ALIAS = "g2d.identity.probe.v1"

/** Alias used to measure StrongBox separately; never used for real data. */
internal const val G2D_STRONGBOX_PROBE_ALIAS = "g2d.identity.probe.strongbox.v1"

internal const val G2D_KEY_SIZE_BITS = 256
internal const val G2D_GCM_IV_BYTES = 12
internal const val G2D_GCM_TAG_BITS = 128
internal const val G2D_GCM_TAG_BYTES = 16
internal const val G2D_KEY_ID_BYTES = 16

/** Domain separator for the identity record envelope. */
internal const val G2D_RECORD_DOMAIN = "g2d.identity.record.v1"

/** Domain separator for probe round trips. */
internal const val G2D_PROBE_DOMAIN = "g2d.identity.probe.v1"

private const val TRANSFORMATION = "AES/GCM/NoPadding"
private const val HEX_DIGITS = "0123456789abcdef"

/**
 * A typed Android Keystore failure.
 *
 * [code] is the stable value sent across the platform channel. The Dart adapter
 * maps it to a storage exception, and the mapping is deliberately asymmetric:
 * only codes that prove the stored bytes are unusable may become "corrupt",
 * because "corrupt" is the only state that permits a destructive reset.
 */
internal class G2dProtectionException(
    val code: String,
    message: String,
    cause: Throwable? = null,
) : Exception(message, cause) {

    companion object {
        /** No usable Android Keystore provider on this device. */
        const val KEYSTORE_UNAVAILABLE = "keystore_unavailable"

        /** The Keystore refused to create a wrapping key. */
        const val KEY_GENERATION_FAILED = "key_generation_failed"

        /** Encrypted data exists but its wrapping key does not. Never regenerated silently. */
        const val KEY_MISSING = "key_missing"

        /** The wrapping key exists but can no longer be used (invalidated by the OS). */
        const val KEY_INVALIDATED = "key_invalidated"

        /** A key exists but cannot be used for this operation. */
        const val KEY_UNUSABLE = "key_unusable"

        /** The ciphertext failed GCM authentication: wrong key or tampered bytes. */
        const val AUTH_FAILED = "auth_failed"

        /** The stored bytes are not a G2-D envelope at all. */
        const val CIPHERTEXT_MALFORMED = "ciphertext_malformed"

        /** The envelope names a different wrapping key than the one on this device. */
        const val KEY_ID_MISMATCH = "key_id_mismatch"

        /** The stored record is older than the last generation committed here. */
        const val STALE_RECORD = "stale_record"

        /** Storage could not be read (not evidence of corruption). */
        const val IO_UNAVAILABLE = "io_unavailable"

        /** A write did not commit. */
        const val WRITE_FAILED = "write_failed"

        /** Unexpected adapter failure. */
        const val INTERNAL_ERROR = "internal_error"
    }
}

/** An iv/ciphertext pair produced by [G2dIdentityKeyring.encrypt]. */
internal class G2dCiphertext(val iv: ByteArray, val ciphertext: ByteArray)

/** Measured characteristics of a Keystore key. */
internal class G2dKeyFacts(
    val hardwareBacked: Boolean,
    val keySizeBits: Int,
    val blockModes: List<String>,
    val encryptionPaddings: List<String>,
)

/**
 * The versioned on-disk envelope.
 *
 * ```text
 * "G2DID1" | version(1) | generation(8) | keyIdLen(1) | keyId | ivLen(1) | iv | ctLen(4) | ciphertext
 * ```
 *
 * `generation` and `keyId` are also bound into the GCM associated data, so
 * editing them in place makes the tag fail rather than reinterpreting the blob.
 */
internal class G2dSealedEnvelope(
    val generation: Long,
    val keyId: ByteArray,
    val iv: ByteArray,
    val ciphertext: ByteArray,
) {

    fun encode(): ByteArray {
        val bytes = ByteArrayOutputStream()
        DataOutputStream(bytes).use { stream ->
            stream.write(MAGIC.toByteArray(Charsets.US_ASCII))
            stream.writeByte(FORMAT_VERSION)
            stream.writeLong(generation)
            stream.writeByte(keyId.size)
            stream.write(keyId)
            stream.writeByte(iv.size)
            stream.write(iv)
            stream.writeInt(ciphertext.size)
            stream.write(ciphertext)
            stream.flush()
        }
        return bytes.toByteArray()
    }

    companion object {
        private const val MAGIC = "G2DID1"
        private const val FORMAT_VERSION = 1
        private const val MIN_ENVELOPE_BYTES = 6 + 1 + 8 + 1 + 1 + 4 + G2D_GCM_TAG_BYTES

        private fun malformed(reason: String): G2dProtectionException =
            G2dProtectionException(
                G2dProtectionException.CIPHERTEXT_MALFORMED,
                "stored identity envelope is not readable ($reason)",
            )

        fun decode(bytes: ByteArray): G2dSealedEnvelope {
            if (bytes.size < MIN_ENVELOPE_BYTES) {
                throw malformed("truncated")
            }
            val buffer = ByteBuffer.wrap(bytes)
            val magic = ByteArray(MAGIC.length)
            buffer.get(magic)
            if (String(magic, Charsets.US_ASCII) != MAGIC) {
                throw malformed("bad magic")
            }
            val version = buffer.get().toInt() and 0xFF
            if (version != FORMAT_VERSION) {
                throw malformed("unsupported version $version")
            }
            val generation = buffer.long
            if (generation < 1L) {
                throw malformed("bad generation")
            }
            val keyIdLength = buffer.get().toInt() and 0xFF
            if (keyIdLength != G2D_KEY_ID_BYTES) {
                throw malformed("bad key id length")
            }
            if (buffer.remaining() < keyIdLength + 1 + G2D_GCM_IV_BYTES + 4 + G2D_GCM_TAG_BYTES) {
                throw malformed("truncated key id")
            }
            val keyId = ByteArray(keyIdLength)
            buffer.get(keyId)
            val ivLength = buffer.get().toInt() and 0xFF
            if (ivLength != G2D_GCM_IV_BYTES) {
                throw malformed("bad iv length")
            }
            if (buffer.remaining() < ivLength + 4 + G2D_GCM_TAG_BYTES) {
                throw malformed("truncated iv")
            }
            val iv = ByteArray(ivLength)
            buffer.get(iv)
            val ciphertextLength = buffer.int
            if (ciphertextLength < G2D_GCM_TAG_BYTES) {
                throw malformed("bad ciphertext length")
            }
            if (buffer.remaining() != ciphertextLength) {
                throw malformed("ciphertext size mismatch")
            }
            val ciphertext = ByteArray(ciphertextLength)
            buffer.get(ciphertext)
            return G2dSealedEnvelope(generation, keyId, iv, ciphertext)
        }
    }
}

/** Associated data for [domain] at [generation] under [keyId]. */
internal fun buildAssociatedData(domain: String, generation: Long, keyId: ByteArray): ByteArray {
    val domainBytes = domain.toByteArray(Charsets.UTF_8)
    val buffer = ByteBuffer.allocate(domainBytes.size + 8 + keyId.size)
    buffer.put(domainBytes)
    buffer.putLong(generation)
    buffer.put(keyId)
    return buffer.array()
}

/** Lowercase hex, used for the non-secret key id in the storage index. */
internal fun encodeKeyId(value: ByteArray): String {
    val builder = StringBuilder(value.size * 2)
    for (byte in value) {
        val unsigned = byte.toInt() and 0xFF
        builder.append(HEX_DIGITS[unsigned ushr 4])
        builder.append(HEX_DIGITS[unsigned and 0x0F])
    }
    return builder.toString()
}

internal fun decodeKeyId(value: String): ByteArray? {
    if (value.isEmpty() || value.length % 2 != 0) {
        return null
    }
    val bytes = ByteArray(value.length / 2)
    for (index in bytes.indices) {
        val high = Character.digit(value[index * 2], 16)
        val low = Character.digit(value[index * 2 + 1], 16)
        if (high < 0 || low < 0) {
            return null
        }
        bytes[index] = ((high shl 4) or low).toByte()
    }
    return bytes
}

internal fun randomKeyId(): ByteArray {
    val bytes = ByteArray(G2D_KEY_ID_BYTES)
    SecureRandom().nextBytes(bytes)
    return bytes
}

/**
 * Creates, inspects, uses and deletes Keystore keys.
 *
 * The class is stateless on purpose: the `KeyStore` handle is re-loaded per
 * operation, so it can never hold a stale view after a key has been deleted or
 * invalidated by the platform.
 */
internal class G2dIdentityKeyring {

    fun loadKeyStore(): KeyStore {
        try {
            val keyStore = KeyStore.getInstance(G2D_KEYSTORE_PROVIDER)
            keyStore.load(null)
            return keyStore
        } catch (error: Exception) {
            throw G2dProtectionException(
                G2dProtectionException.KEYSTORE_UNAVAILABLE,
                "the Android Keystore is not available on this device",
                error,
            )
        }
    }

    fun hasKey(alias: String): Boolean {
        val keyStore = loadKeyStore()
        return try {
            keyStore.containsAlias(alias)
        } catch (error: Exception) {
            throw G2dProtectionException(
                G2dProtectionException.KEYSTORE_UNAVAILABLE,
                "the Android Keystore could not be queried",
                error,
            )
        }
    }

    /**
     * Returns the key at [alias], creating it only when [allowCreate] is true.
     *
     * `allowCreate = false` is the load path: when encrypted data exists and the
     * key is gone, the only honest outcome is [G2dProtectionException.KEY_MISSING].
     * Generating a replacement key there would turn "your identity cannot be
     * decrypted" into a silent fresh start that looks successful.
     */
    fun ensureKey(alias: String, allowCreate: Boolean, strongBox: Boolean = false): SecretKey {
        val keyStore = loadKeyStore()
        val existing = try {
            keyStore.getKey(alias, null) as? SecretKey
        } catch (error: UnrecoverableKeyException) {
            throw G2dProtectionException(
                G2dProtectionException.KEY_INVALIDATED,
                "the identity wrapping key is no longer recoverable",
                error,
            )
        } catch (error: Exception) {
            throw G2dProtectionException(
                G2dProtectionException.KEYSTORE_UNAVAILABLE,
                "the identity wrapping key could not be read",
                error,
            )
        }
        if (existing != null) {
            return existing
        }
        if (!allowCreate) {
            throw G2dProtectionException(
                G2dProtectionException.KEY_MISSING,
                "encrypted identity data exists but its wrapping key is missing",
            )
        }
        return createKey(alias, strongBox)
    }

    /**
     * Generates an AES-256-GCM wrapping key in the Keystore.
     *
     * The key is non-exportable by construction, requires no user authentication
     * (identity use is not interactive), and cannot be used with an attacker
     * chosen iv because randomized encryption is required.
     */
    fun createKey(alias: String, strongBox: Boolean): SecretKey {
        try {
            val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, G2D_KEYSTORE_PROVIDER)
            val builder = KeyGenParameterSpec.Builder(
                alias,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(G2D_KEY_SIZE_BITS)
                .setRandomizedEncryptionRequired(true)
                .setUserAuthenticationRequired(false)
            if (strongBox) {
                if (Build.VERSION.SDK_INT < Build.VERSION_CODES.P) {
                    throw G2dProtectionException(
                        G2dProtectionException.KEY_GENERATION_FAILED,
                        "StrongBox keys require Android 9 (API 28) or newer",
                    )
                }
                builder.setIsStrongBoxBacked(true)
            }
            generator.init(builder.build())
            return generator.generateKey()
        } catch (error: G2dProtectionException) {
            throw error
        } catch (error: Exception) {
            throw G2dProtectionException(
                G2dProtectionException.KEY_GENERATION_FAILED,
                "the Android Keystore refused to create a wrapping key",
                error,
            )
        }
    }

    /**
     * Measures a key's real characteristics.
     *
     * `isInsideSecureHardware` is the platform's own answer, taken from the key's
     * [KeyInfo]. It is the only evidence this project accepts for a
     * hardware-backed claim; the API level and the presence of a Keystore are
     * never treated as evidence. Returns null when the key is absent or when the
     * platform will not describe it.
     */
    fun inspectKey(alias: String): G2dKeyFacts? {
        val keyStore = loadKeyStore()
        val key = try {
            keyStore.getKey(alias, null) as? SecretKey
        } catch (error: Exception) {
            return null
        }
        if (key == null) {
            return null
        }
        return try {
            val factory = SecretKeyFactory.getInstance(key.algorithm, G2D_KEYSTORE_PROVIDER)
            // `SecretKeyFactory.getKeySpec` is declared on the generic `KeySpec`
            // bound, so the platform type is `KeySpec!` and the compiler cannot
            // prove it returns a `KeyInfo`, even when one is requested. A checked
            // cast keeps this honest in both directions: a real `KeyInfo` is
            // measured as before, and anything else is reported as "the platform
            // would not describe this key" by returning null — never as
            // hardware-backed, and never as "not hardware-backed" either, which
            // would be a measurement we did not make.
            val specs = factory.getKeySpec(key, KeyInfo::class.java)
            val info = specs as? KeyInfo ?: return null
            G2dKeyFacts(
                hardwareBacked = info.isInsideSecureHardware,
                keySizeBits = info.keySize,
                blockModes = info.blockModes.toList(),
                encryptionPaddings = info.encryptionPaddings.toList(),
            )
        } catch (error: Exception) {
            null
        }
    }

    fun deleteKeyIfPresent(alias: String) {
        try {
            val keyStore = loadKeyStore()
            if (keyStore.containsAlias(alias)) {
                keyStore.deleteEntry(alias)
            }
        } catch (error: Exception) {
            throw G2dProtectionException(
                G2dProtectionException.KEYSTORE_UNAVAILABLE,
                "the Android Keystore could not remove a key",
                error,
            )
        }
    }

    /**
     * Encrypts [plaintext] under [key] with a Keystore-chosen iv.
     *
     * [plaintext] is the caller's buffer; the caller is responsible for zeroing
     * it once this returns.
     */
    fun encrypt(key: SecretKey, plaintext: ByteArray, associatedData: ByteArray): G2dCiphertext {
        try {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, key)
            cipher.updateAAD(associatedData)
            val ciphertext = cipher.doFinal(plaintext)
            return G2dCiphertext(cipher.iv, ciphertext)
        } catch (error: KeyPermanentlyInvalidatedException) {
            throw G2dProtectionException(
                G2dProtectionException.KEY_INVALIDATED,
                "the identity wrapping key has been invalidated",
                error,
            )
        } catch (error: GeneralSecurityException) {
            throw G2dProtectionException(
                G2dProtectionException.KEY_UNUSABLE,
                "the identity wrapping key could not encrypt data",
                error,
            )
        }
    }

    /**
     * Authenticated decryption. Fails closed: a tag mismatch is
     * [G2dProtectionException.AUTH_FAILED], never a partial or best-effort result.
     */
    fun decrypt(
        key: SecretKey,
        iv: ByteArray,
        ciphertext: ByteArray,
        associatedData: ByteArray,
    ): ByteArray {
        try {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(G2D_GCM_TAG_BITS, iv))
            cipher.updateAAD(associatedData)
            return cipher.doFinal(ciphertext)
        } catch (error: AEADBadTagException) {
            throw G2dProtectionException(
                G2dProtectionException.AUTH_FAILED,
                "stored identity data failed authentication",
                error,
            )
        } catch (error: KeyPermanentlyInvalidatedException) {
            throw G2dProtectionException(
                G2dProtectionException.KEY_INVALIDATED,
                "the identity wrapping key has been invalidated",
                error,
            )
        } catch (error: GeneralSecurityException) {
            throw G2dProtectionException(
                G2dProtectionException.CIPHERTEXT_MALFORMED,
                "stored identity data could not be decrypted",
                error,
            )
        }
    }
}
